int32_t crypto_hash_common_get_state(crypto_hash_type hash_type, uint32_t *state, uint32_t *state_size)
{
    int32_t ret;
    uint32_t i;

    for (i = 0; i < crypto_array_size(g_hash_state); i++) {
        if (g_hash_state[i].hash_type == crypto_hash_remove_hmac_flag(hash_type)) {
            break;
        }
    }
    crypto_chk_return(i >= crypto_array_size(g_hash_state), ERROR_INVALID_PARAM, "wrong hash type\n");

    ret = memcpy_s(state, *state_size, g_hash_state[i].g_state, g_hash_state[i].val_size);
    crypto_chk_return(ret != EOK, ERROR_MEMCPY_S, "memcpy_s failed\n");

    *state_size = g_hash_state[i].val_size;
    return CRYPTO_SUCCESS;
}

int32_t crypto_hash_common_type_check(crypto_hash_type hash_type)
{
    uint32_t i;

    for (i = 0; i < crypto_array_size(g_hash_state); i++) {
        if (g_hash_state[i].hash_type == crypto_hash_remove_hmac_flag(hash_type)) {
            return CRYPTO_SUCCESS;
        }
    }
    return CRYPTO_FAILURE;
}

const uint8_t *crypto_hash_common_get_state_iv(crypto_hash_type hash_type, uint32_t *iv_size)
{
    uint32_t i;

    for (i = 0; i < crypto_array_size(g_hash_state); i++) {
        if (g_hash_state[i].hash_type == crypto_hash_remove_hmac_flag(hash_type)) {
            *iv_size = g_hash_state[i].val_size;
            return g_hash_state[i].g_state;
        }
    }
    return NULL;
}


void crypto_hash_common_length_add(uint32_t length[2], uint32_t addition)
{
    uint32_t diff = 0;
    if (length[1] > length[1] + addition) {
        length[0]++;
        diff = 0xFFFFFFFF - length[1] + 1;
        length[1] = addition - diff;
        return;
    }
    length[1] += addition;
}