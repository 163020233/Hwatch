#if CORE == BT

#define MODE_ENABLE_DELAY_US 100
#define BCPU_TRACE_MEM_REGION_END (BCPU_TRACE_MEM_REGION_START + CPU_TRACE_MEM_REGION_LENGTH)

void bt_cpu_trace_enable(void)
{
    // 打开时钟
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_MONITOR_CLOCK_REG, BCPU_TRACE_CTL_RB_CFG_MONITOR_WR_CLKEN_OFFSET);
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_MONITOR_CLOCK_REG, BCPU_TRACE_CTL_RB_CFG_MONITOR_SRC_CLKEN_OFFSET);
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_MONITOR_CLOCK_REG, BCPU_TRACE_CTL_RB_CFG_CPU_TRACE_CLKEN_OFFSET);
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_MONITOR_CLOCK_REG, BCPU_TRACE_CTL_RB_CFG_BCPU_CLKEN_OFFSET);
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_MONITOR_CLOCK_REG, BCPU_TRACE_CTL_RB_CFG_TRACE_MEM_CLKEN_OFFSET);
    // 长度
    reg16_write(BCPU_TRACE_CTL_RB_CFG_SAMPLE_LENGTH_L_REG,
        CPU_TRACE_MEM_REGION_LENGTH & BCPU_TRACE_CTL_RB_CFG_SAMPLE_LENGTH_L_MASK);
    reg16_write(BCPU_TRACE_CTL_RB_CFG_SAMPLE_LENGTH_H_REG,
        (CPU_TRACE_MEM_REGION_LENGTH >> BCPU_TRACE_CTL_RB_CFG_SAMPLE_LENGTH_L_LEN) &
        BCPU_TRACE_CTL_RB_CFG_SAMPLE_LENGTH_H_MASK);
    // 起始地址
    reg16_write(BCPU_TRACE_CTL_RB_CFG_SAMPLE_START_ADDR_L_REG,
        BCPU_TRACE_MEM_REGION_START & BCPU_TRACE_CTL_RB_CFG_SAMPLE_START_ADDR_L_MASK);
    reg16_write(BCPU_TRACE_CTL_RB_CFG_SAMPLE_START_ADDR_H_REG,
        (BCPU_TRACE_MEM_REGION_START >> BCPU_TRACE_CTL_RB_CFG_SAMPLE_START_ADDR_L_LEN) &
        BCPU_TRACE_CTL_RB_CFG_SAMPLE_START_ADDR_H_MASK);
    // 终止地址
    reg16_write(BCPU_TRACE_CTL_RB_CFG_SAMPLE_END_ADDR_L_REG,
        BCPU_TRACE_MEM_REGION_END & BCPU_TRACE_CTL_RB_CFG_SAMPLE_END_ADDR_L_MASK);
    reg16_write(BCPU_TRACE_CTL_RB_CFG_SAMPLE_END_ADDR_H_REG,
        (BCPU_TRACE_MEM_REGION_END >> BCPU_TRACE_CTL_RB_CFG_SAMPLE_END_ADDR_L_LEN) &
        BCPU_TRACE_CTL_RB_CFG_SAMPLE_END_ADDR_H_MASK);
    // 循环模式
    reg16_setbits(BCPU_TRACE_CTL_RB_CFG_SAMPLE_MODE_REG,
        BCPU_TRACE_CTL_RB_CFG_SAMPLE_MODE_OFFSET, BCPU_TRACE_CTL_RB_CFG_SAMPLE_MODE_LEN, 0x01);
    // Sync
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_SAMPLE_MODE_REG, BCPU_TRACE_CTL_RB_CFG_SAMPLE_EN_OFFSET);
    uapi_tcxo_delay_us(MODE_ENABLE_DELAY_US);
    // 使能
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_SAMPLE_MODE_REG, BCPU_TRACE_CTL_RB_CFG_SAMPLE_SYNC_OFFSET);
    reg16_setbit(BCPU_TRACE_CTL_RB_CFG_CPU_TRACE_REG, BCPU_TRACE_CTL_RB_CFG_CPU_TRACE_EN_OFFSET);
}

void bt_cpu_trace_disable(void)
{
    dsb(); /* flush cpu before disable trace */
    reg16_write(BCPU_TRACE_CTL_RB_CFG_CPU_TRACE_REG, 0x0);
    reg16_write(BCPU_TRACE_CTL_RB_CFG_SAMPLE_MODE_REG, 0x1);
}

#endif